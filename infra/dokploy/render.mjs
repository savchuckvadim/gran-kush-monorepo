#!/usr/bin/env node
// Renders the Dokploy files of every installation from templates/:
//   infra/dokploy/<brand>/docker-compose.yml and infra/dokploy/<brand>/.env.example
// Installations, domains and names: packages/brand (its dist, built on pnpm install).
//
//   node infra/dokploy/render.mjs          write the files
//   node infra/dokploy/render.mjs --check  exit 1 when a file is stale (CI)
//
// Service names are YAML keys and cannot come from the environment, and they must be unique on
// the shared dokploy-network — hence a rendered file per brand instead of one file with env.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const { BRANDS, INSTALLATIONS } = createRequire(import.meta.url)(
    join(root, "packages/brand/dist/index.js")
);

const SERVER_WIDE = /^# >>> server-wide.*\n[\s\S]*?^# <<< server-wide\n/gm;
const SERVER_WIDE_MARKERS = /^# (>>>|<<<) server-wide.*\n/gm;

const render = (template, code, installation) => {
    const name = BRANDS[code].name;
    const kept = installation.serverServices
        ? template.replace(SERVER_WIDE_MARKERS, "")
        : template.replace(SERVER_WIDE, "");
    return kept
        .replaceAll("__BRAND_NAME__", name)
        .replaceAll("__BRAND__", code)
        .replaceAll("__DOMAIN__", installation.domain)
        .replaceAll("__CABINET__", installation.cabinetSubdomain)
        .replaceAll(
            "__JANITOR_ALERTS__",
            installation.serverServices ? ` and disk alerts from ${code}-janitor` : ""
        );
};

const HEADER =
    "# Generated by infra/dokploy/render.mjs from templates/ — edit the template, not this file.\n";

const files = [
    ["templates/docker-compose.template.yml", "docker-compose.yml"],
    ["templates/env.template", ".env.example"],
];

const check = process.argv.includes("--check");
let stale = 0;

for (const [code, installation] of Object.entries(INSTALLATIONS)) {
    for (const [source, target] of files) {
        const template = readFileSync(join(here, source), "utf8").replace(/\r\n/g, "\n");
        const output = HEADER + render(template, code, installation);
        const path = join(here, code, target);
        if (check) {
            const current = existsSync(path)
                ? readFileSync(path, "utf8").replace(/\r\n/g, "\n")
                : "";
            if (current !== output) {
                console.error(`stale: ${relative(root, path)} — run node infra/dokploy/render.mjs`);
                stale += 1;
            }
            continue;
        }
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, output);
        console.log(`wrote ${relative(root, path)}`);
    }
}

if (stale > 0) process.exit(1);
